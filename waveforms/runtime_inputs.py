"""Delivered, hash-verified public inputs. No local-archive or source-project lookup."""
import hashlib
import json
from pathlib import Path
import numpy as np
import pandas as pd
import torch
from .artifacts import sha, safe_relative
from .basis_source import SelectedBasis

FORMAT = 'waveforms-runtime-v1'
ASSETS = {'dd_N64.npz','dd_N128.npz','dd_N256.npz','dd_replay.csv','cfo_stage1.pt'}
DD_KEYS = {'w','q_nominal','q_test','ensemble_power','labels','permutation',
           'example_tau','example_nu','example_gains','Learned_mask','OTFS_mask','AFDM_mask'}


def delivered_root():
    return Path(__file__).resolve().parent/'data'


def is_runtime_root(root):
    root=Path(root)
    return root.resolve()==delivered_root() or (root/'manifest.json').exists() or (root/'dd_N64.npz').exists()


def array_hash(array):
    array=np.ascontiguousarray(array)
    digest=hashlib.sha256(str(array.dtype).encode())
    digest.update(np.asarray(array.shape,dtype=np.int64).tobytes());digest.update(array.tobytes())
    return digest.hexdigest()


def verify_runtime(root=None):
    root=Path(root) if root is not None else delivered_root()
    path=root/'manifest.json'
    if path.is_symlink() or not path.is_file():raise ValueError('Delivered input manifest missing; restore waveforms/data from Git')
    manifest=json.loads(path.read_text())
    if manifest.get('format')!=FORMAT or set(manifest.get('files',{}))!=ASSETS:
        raise ValueError('Delivered input format/file inventory differs')
    for name,entry in manifest['files'].items():
        path=root/safe_relative(name)
        if path.is_symlink() or not path.is_file() or path.stat().st_size!=entry['bytes'] or sha(path)!=entry['sha256']:
            raise ValueError(f'Missing or altered delivered input: {name}; restore it from Git')
    if set(manifest.get('dd',{}))!={'64','128','256'}:raise ValueError('Delivered dimension inventory differs')
    return manifest


class RuntimeEvidence:
    """Same selected-basis/evidence contract as the optional full scaling archive.

    Sample H/A is regenerated by the existing workflow from the exact saved paths.
    Q, mean powers, supports, mappings and saved BER are copied evidence, not fits.
    """
    def __init__(self,root,n):
        from .scaling_evidence import SIZES,GRIDS
        from .delay_doppler import classical
        if n not in SIZES:raise ValueError('Available sizes: N64/K24, N128/K48, N256/K96')
        self.root,self.n,self.k=Path(root),n,SIZES[n]
        self.manifest=verify_runtime(self.root)
        entry=self.manifest['dd'][str(n)]
        if entry['N']!=n or entry['K']!=self.k or entry['file']!=f'dd_N{n}.npz':
            raise ValueError('Delivered N/K identity differs; no substitution')
        with np.load(self.root/entry['file'],allow_pickle=False) as data:
            if set(data.files)!=DD_KEYS:raise ValueError('Delivered DD fields differ')
            arrays={key:data[key].copy() for key in data.files}
        for key,array in arrays.items():
            if array_hash(array)!=entry['arrays'][key]['array_sha256']:
                raise ValueError(f'Delivered source-array identity differs: {key}')
        w=arrays['w']; labels=arrays['labels'];order=arrays['permutation']
        if w.shape!=(n,n) or w.dtype!=np.complex128:raise ValueError('Delivered W shape/dtype differs')
        if labels.shape!=(n,) or order.shape!=(n,) or labels.dtype!=np.int64 or order.dtype!=np.int64:
            raise ValueError('Delivered group mapping shape/type differs')
        if not np.array_equal(order,np.argsort(labels,kind='stable')) or not np.array_equal(np.sort(order),np.arange(n)):
            raise ValueError('Delivered native group permutation differs')
        if not np.array_equal(np.unique(labels),np.arange(len(np.unique(labels)))):raise ValueError('Invalid coupling group IDs')
        for key in ('q_nominal','q_test','ensemble_power'):
            a=arrays[key]
            if a.shape!=(n,n) or a.dtype!=np.float64 or not np.isfinite(a).all() or (a<0).any():raise ValueError('Invalid delivered coupling statistic')
        for key in ('example_tau','example_nu','example_gains'):
            if arrays[key].shape!=(3,) or not np.isfinite(arrays[key]).all():raise ValueError('Invalid delivered sample paths')
        controls=classical(n,*GRIDS[n]);self.records={}
        for name in ('Learned','OTFS','AFDM'):
            mask=arrays[name+'_mask']
            if mask.shape!=(n,n) or mask.dtype!=np.bool_ or not (mask.sum(-1)==self.k).all():raise ValueError('Delivered fixed support differs')
            self.records[name]=dict(w=w if name=='Learned' else controls[name].numpy(),mask_nominal=mask)
        self.records['Learned'].update({key:value for key,value in arrays.items() if not key.endswith('_mask')})
        original=entry['identity']
        self.identity={**original,'file':entry['file'],'file_sha256':self.manifest['files'][entry['file']]['sha256'],
                       'original_file':original['file'],'original_file_sha256':original['file_sha256']}
        self.metadata=self.manifest['dd_protocol']
        self.selected=SelectedBasis(torch.from_numpy(w.copy()),torch.from_numpy(arrays['Learned_mask'].copy()),
            dict(source=entry['file']+'#w',file_sha256=self.identity['file_sha256'],
                 original_matrix_file_sha256=original['file_sha256'],provenance=original['provenance'],
                 N=n,K=self.k,basis_mode='load_existing',
                 training_status='Not run here; exact delivered archived trained basis',selection=entry['selection'])).validate()

    def matches(self,basis):
        return torch.equal(basis.matrix,self.selected.matrix) and torch.equal(basis.fixed_q_mask,self.selected.fixed_q_mask)

    def ber(self):
        spec=self.manifest['replay']
        frame=pd.read_csv(self.root/spec['file'],dtype=spec['dtypes'])
        if len(frame)!=spec['rows']:raise ValueError('Delivered replay row inventory differs')
        frame.index=pd.Index(frame.pop('_source_row').to_numpy(),name=None)
        frame=frame[(frame.N==self.n)&(frame.scenario=='nominal')&(frame.slicer=='raw')&frame.receiver.isin(['fixed_nominal','full'])].copy()
        frame['receiver']=frame.receiver.replace({'fixed_nominal':'fixed'})
        if len(frame)!=96 or set(frame.waveform)!={'Learned','OTFS','AFDM'}:raise ValueError('Incomplete delivered replay evidence')
        return frame

    def input_hashes(self):
        names=('manifest.json',self.identity['file'],self.manifest['replay']['file'])
        return {name:sha(self.root/name) for name in names}


def load_cfo(root):
    from .residual_cfo import load_qualified_checkpoint
    manifest=verify_runtime(root);entry=manifest['cfo']
    expected=manifest['files'][entry['file']]['sha256']
    if entry['file']!='cfo_stage1.pt' or expected!=entry['original_sha256']:
        raise ValueError('Delivered CFO checkpoint identity differs')
    w,r,checks=load_qualified_checkpoint(Path(root)/entry['file'],expected)
    return w,r,{**checks,'input_source':'delivered waveforms/data; exact original checkpoint bytes',
                'input_manifest_sha256':sha(Path(root)/'manifest.json')}
